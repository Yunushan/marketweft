import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures.mjs'
import { catalogContents } from './catalog-fixtures.mjs'

async function open(page) {
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open paper ledger' }).click()
  await expect(page.getByRole('heading', { name: 'Paper ledger', exact: true })).toBeFocused()
}

test('paper ledger reconciles reservations, unique partial fills, realized profit and kill switch offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await open(page)
  await page.getByRole('button', { name: 'Start paper demo' }).click()
  const account = page.getByRole('region', { name: 'Simulated account' })
  const field = (label, value) => expect(account.getByText(label, { exact: true })
    .locator('xpath=following-sibling::dd')).toHaveText(value)
  const receipt = event => account.getByRole('table', { name: 'Paper receipts' })
    .getByRole('row', { name: new RegExp('^' + event) })
  const next = page.getByRole('button', { name: 'Next event time' })
  const previous = page.getByRole('button', { name: 'Previous event time' })
  await field('Cash balance', '1000')
  await field('Reserved cash', '503')
  await field('Available cash', '497')
  await next.click()
  await expect(receipt('EARLY')).toContainText('Price time ineligible')
  await field('Cash balance', '1000')
  await next.click()
  await field('Cash balance', '801.6')
  await field('Reserved cash', '300.6')
  await expect(receipt('FILL1')).toHaveCount(1)
  await expect(receipt('FILL1')).toContainText('2.4')
  await expect(account.getByRole('table', { name: 'Paper orders' })).toContainText('Partially filled')
  await page.getByRole('button', { name: 'Final account' }).click()
  await field('Cash balance', '663.7')
  await field('Reserved cash', '0')
  await field('Realized profit and loss', '13')
  await expect(account.getByRole('status')).toContainText('Halted')
  await expect(account.getByRole('table', { name: 'Paper orders' }).getByRole('row', { name: /^PENDING/ }))
    .toContainText('Canceled')
  await expect(receipt('TOO-LATE')).toContainText('Account halted')
  await previous.click()
  await previous.click()
  await field('Reserved cash', '122.4')
  await expect(account.getByRole('status')).toContainText('Active')
  await page.getByLabel('Observed through (UTC)').fill('2025-04-03T14:02:00Z')
  await page.getByRole('button', { name: 'Run paper replay' }).click()
  await field('Cash balance', '801.6')
  await expect(receipt('TOO-LATE')).toHaveCount(0)
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await expect(page.getByRole('button', { name: 'Open paper ledger' })).toBeFocused()
})

test('paper depth shares recorded liquidity and audits the exact halt and rewind offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  const original = await catalogContents(page)
  await context.setOffline(true)
  await open(page)
  const fixture = name => readFile(new URL('../../../crates/core/tests/fixtures/synthetic-paper-depth-' + name + '.csv', import.meta.url))
  const [controls, depth] = await Promise.all([fixture('controls'), fixture('liquidity')])
  await page.getByLabel('Paper depth controls CSV').setInputFiles({ name: 'controls.csv', mimeType: 'text/csv', buffer: controls })
  await page.getByLabel('Paper order book CSV').setInputFiles({ name: 'depth.csv', mimeType: 'text/csv', buffer: depth })
  await page.getByRole('button', { name: 'Load paper depth replay' }).click()
  const account = page.getByRole('region', { name: 'Simulated account' })
  const value = name => account.getByText(name, { exact: true }).locator('..').locator('dd')
  const ledger = account.getByRole('table', { name: 'Paper receipts' })
  const fills = ledger.locator('tbody tr').filter({ has: page.getByRole('cell', { name: 'fill', exact: true }) })
  const cutoff = async second => {
    await page.getByLabel('Observed through (UTC)').fill('2025-06-02T14:00:0' + second + 'Z')
    await page.getByRole('button', { name: 'Run paper replay' }).click()
  }
  const download = async () => {
    const pending = page.waitForEvent('download')
    await account.getByRole('button', { name: 'Download paper depth receipts' }).click()
    const file = await pending
    expect(file.suggestedFilename()).toBe('paper-depth-receipts.csv')
    return readFile(await file.path(), 'utf8')
  }
  await expect(fills).toHaveCount(0)
  await cutoff(2)
  await expect(value('Cash balance')).toHaveText('799.8')
  await expect(value('Reserved cash')).toHaveText('303.3')
  await expect(fills.first()).toContainText('DEPTH-9007199254740994-1')
  const first = await download()
  expect(first).toContain('"NASDAQ:NVDA","controls.csv","depth.csv"')
  expect(first).toMatch(/,fill,"B","DEPTH-9007199254740994-1",2025-06-02T14:00:01Z,2,99,accepted,-200\.2,2\.2,0\r\n/)
  await cutoff(3)
  await expect(fills).toHaveCount(1)
  await cutoff(4)
  await expect(fills).toHaveCount(3)
  await expect(value('Cash balance')).toHaveText('599.6')
  await cutoff(6)
  await expect(account.getByText(/Sequence gap. Expected 9007199254740997/)).toBeVisible()
  await expect(fills).toHaveCount(3)
  await cutoff(7)
  await expect(fills).toHaveCount(4)
  await expect(value('Cash balance')).toHaveText('697.5')
  await expect(value('Realized profit and loss')).toHaveText('-2.2')
  await page.getByRole('button', { name: 'Final account' }).click()
  await expect(account.getByRole('status')).toContainText('Halted')
  await expect(fills).toHaveCount(4)
  await expect(value('Reserved cash')).toHaveText('0')
  await cutoff(2)
  expect(await download()).toBe(first)
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  expect(await catalogContents(page)).toEqual(original)
})

test('paper input rejects conflicting events and exposes limit rejections without changing the catalog', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('heading', { name: 'Research terminal' }).waitFor()
  const original = await catalogContents(page)
  await open(page)
  const csv = await readFile(new URL('../../../crates/core/tests/fixtures/synthetic-paper-events.csv', import.meta.url), 'utf8')
  const input = content => page.getByLabel('Paper events CSV').setInputFiles({
    name: 'paper.csv', mimeType: 'text/csv', buffer: Buffer.from(content),
  })
  const load = page.getByRole('button', { name: 'Load paper ledger' })
  await input(csv.replace('4,49,Q1', '5,49,Q1'))
  await load.click()
  await expect(page.getByRole('alert')).toContainText('event ID has conflicting fields')
  await input(csv)
  await load.click()
  await expect(page.getByText('paper.csv', { exact: true })).toBeVisible()
  await page.getByLabel('Position limit (shares)').fill('3')
  await page.getByRole('button', { name: 'Run paper replay' }).click()
  const result = page.getByRole('table', { name: 'Paper receipts' }).getByRole('row', { name: /^OPEN/ })
  await expect(result).toContainText('Position limit')
  await page.getByLabel('Starting cash').fill('-10')
  await page.getByRole('button', { name: 'Run paper replay' }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid paper account')
  await expect(result).toContainText('Position limit')
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await page.getByRole('button', { name: 'Return to workspace' }).click()
  expect(await catalogContents(page)).toEqual(original)
})
