import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures.mjs'
import { catalogContents } from './catalog-fixtures.mjs'

const utc = minute => '2025-06-02T14:0' + minute + ':00Z'

test('joint portfolio paths preserve return pairs, cutoff coverage and exact fees offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  const original = await catalogContents(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open universe replay' }).click()
  await page.getByRole('button', { name: 'Start listing risk demo' }).click()
  const screen = page.getByRole('region', { name: 'Universe screen' })
  await screen.getByText('Correlated portfolio scenarios', { exact: true }).click()
  const view = screen.getByRole('region', { name: 'Correlated portfolio scenarios', exact: true })
  const cutoffs = async (effective, known) => {
    await page.getByLabel('Effective time (UTC)').fill(utc(effective))
    await page.getByLabel('Known time (UTC)').fill(utc(known))
    await page.getByRole('button', { name: 'Run as-of query' }).click()
  }
  const run = view.getByRole('button', { name: 'Run portfolio scenarios' })
  const status = view.getByRole('status')
  const table = view.getByRole('table', { name: 'Portfolio scenario percentiles' })
  const metric = name => table.getByRole('row', { name: new RegExp('^' + name) }).getByRole('cell').nth(1)
  const download = async () => {
    const pending = page.waitForEvent('download')
    await view.getByRole('button', { name: 'Download scenario paths' }).click()
    const saved = await pending
    expect(saved.suggestedFilename()).toBe('portfolio-scenarios.csv')
    return (await readFile(await saved.path(), 'utf8')).trimEnd().split('\r\n')
  }

  await cutoffs(6, 6)
  await view.getByRole('combobox', { name: 'Scenario listing 1', exact: true }).selectOption('A')
  await view.getByRole('combobox', { name: 'Scenario listing 2', exact: true }).selectOption('B')
  await run.click()
  await expect(status).toHaveText('4 / 6 complete return vectors · 0 / 10 paths ended below starting value')
  await expect(metric('Ending portfolio value')).toHaveText('100')
  const originalPaths = await download()
  expect(originalPaths).toHaveLength(11)
  expect(originalPaths[1]).toBe(
    '"Synthetic listing risk membership","Synthetic listing risk closes","2025-06-02T14:00:00Z","2025-06-02T14:06:00Z","2025-06-02T14:06:00Z",60,100,0,9007199254740993,12,"A=5000|B=5000",6,4,1,100,0,0',
  )

  await cutoffs(6, 7)
  await expect(status).toContainText('6 / 6 complete return vectors')
  await cutoffs(6, 8)
  await expect(status).toContainText('4 / 6 complete return vectors')
  const coverage = view.getByRole('table', { name: 'Portfolio scenario coverage' })
  await expect(coverage.getByRole('row', { name: /^A / }).getByRole('cell').last()).toHaveText('4 / 6')
  await cutoffs(6, 6)
  expect(await download()).toEqual(originalPaths)

  const blockSize = view.getByLabel('Moves per sampled block', { exact: true })
  await blockSize.fill('2')
  await run.click()
  const eligible = view.getByText(/^Eligible historical blocks/)
  await expect(eligible).toHaveText('Eligible historical blocks of 2 moves · 2')
  const blockPaths = await download()
  expect(blockPaths[0]).toMatch(/,moves_per_block,eligible_blocks$/)
  expect(blockPaths[1]).toBe(originalPaths[1] + ',2,2')
  await cutoffs(6, 7)
  await expect(eligible).toHaveText('Eligible historical blocks of 2 moves · 5')
  await cutoffs(6, 8)
  await expect(eligible).toHaveText('Eligible historical blocks of 2 moves · 3')
  await cutoffs(6, 6)
  expect(await download()).toEqual(blockPaths)
  await blockSize.fill('4')
  await run.click()
  await expect(view.getByRole('alert')).toHaveText('No complete return block of this size is visible at the selected cutoffs.')
  expect(await download()).toEqual(blockPaths)
  await blockSize.fill('1')
  await run.click()
  await expect(eligible).toHaveCount(0)
  expect(await download()).toEqual(originalPaths)

  await view.getByRole('button', { name: 'Add scenario listing' }).click()
  await view.getByRole('combobox', { name: 'Scenario listing 3', exact: true }).selectOption('A')
  await view.getByLabel('Listing 1 weight (basis points)').fill('4000')
  await view.getByLabel('Listing 2 weight (basis points)').fill('4000')
  await view.getByLabel('Listing 3 weight (basis points)').fill('2000')
  await run.click()
  await expect(view.getByRole('alert')).toHaveText('Choose distinct listing IDs from the supplied universe.')
  expect(await download()).toEqual(originalPaths)
  await view.getByRole('button', { name: 'Remove listing 3' }).click()
  await view.getByLabel('Listing 1 weight (basis points)').fill('5000')
  await view.getByLabel('Listing 2 weight (basis points)').fill('5000')
  await cutoffs(1, 1)
  await view.getByLabel('Rebalance fee (basis points)').fill('100')
  await view.getByLabel('Moves per portfolio path').fill('1')
  await run.click()
  await expect(status).toHaveText('1 / 1 complete return vectors · 10 / 10 paths ended below starting value')
  await expect(metric('Ending portfolio value')).toHaveText('99.95')
  await expect(metric('Peak-to-trough drawdown')).toHaveText('0.05%')
  await expect(metric('Turnover fees')).toHaveText('0.05')
  const fees = await download()
  expect(fees[1].endsWith(',1,99.95,0.05,0.05')).toBe(true)
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await page.getByRole('button', { name: 'Return to workspace' }).click()
  expect(await catalogContents(page)).toEqual(original)
})

test('portfolio minimum variance tracks shared returns and exports zero weights offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  const original = await catalogContents(page)
  await context.setOffline(true)
  const fixture = name => readFile(new URL('../../../crates/core/tests/fixtures/synthetic-listing-risk-' + name + '.csv', import.meta.url), 'utf8')
  const [members, closes] = await Promise.all([fixture('membership'), fixture('prices')])
  const membership = members.trimEnd() + '\nRISK,C-ADD,C,DEMO:GAMMA,2025-06-02T14:00:00Z,2025-06-02T14:00:00Z,add\n'
  const prices = closes.trimEnd().replaceAll(',90\n', ',120\n') + '\n' + [
    'RISK,C,2025-06-02T14:00:00Z,2025-06-02T14:00:00Z,10',
    'RISK,C,2025-06-02T14:01:00Z,2025-06-02T14:01:00Z,10',
    'RISK,C,2025-06-02T14:02:00Z,2025-06-02T14:07:00Z,10',
  ].join('\n')
  const upload = (name, content) => ({ name, mimeType: 'text/csv', buffer: Buffer.from(content) })
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open universe replay' }).click()
  await page.getByLabel('Universe membership CSV').setInputFiles(upload('membership.csv', membership))
  await page.getByRole('button', { name: 'Load universe', exact: true }).click()
  const screen = page.getByRole('region', { name: 'Universe screen' })
  await screen.getByLabel('Universe prices CSV').setInputFiles(upload('closes.csv', prices))
  await screen.getByRole('button', { name: 'Load prices', exact: true }).click()
  await screen.getByText('Portfolio minimum variance', { exact: true }).click()
  const view = screen.getByRole('region', { name: 'Portfolio minimum variance', exact: true })
  for (const id of ['C', 'A', 'B']) await view.getByRole('checkbox', { name: new RegExp('^' + id + ' ') }).check()
  const query = async known => {
    await page.getByLabel('Effective time (UTC)').fill(utc(6))
    await page.getByLabel('Known time (UTC)').fill(utc(known))
    await page.getByRole('button', { name: 'Run as-of query' }).click()
  }
  const run = view.getByRole('button', { name: 'Estimate minimum variance', exact: true })
  const status = view.getByRole('status')
  const table = view.getByRole('table', { name: 'Minimum variance allocation by listing' })
  const cells = id => table.getByRole('row', { name: new RegExp('^' + id + ' ') }).getByRole('cell')
  const download = async () => {
    const pending = page.waitForEvent('download')
    await view.getByRole('button', { name: 'Download minimum variance', exact: true }).click()
    const file = await pending
    expect(file.suggestedFilename()).toBe('portfolio-minimum-variance.csv')
    return readFile(await file.path(), 'utf8')
  }
  await query(6)
  await run.click()
  await expect(status).toHaveText('1 of 6 common intervals')
  await expect(cells('C')).toHaveText(['1', '—', '—'])
  const early = await download()
  expect(early.split('\r\n')[3]).toContain(',6,1,"C",1,,,,,,,,')
  await query(7)
  await expect(status).toHaveText('2 of 6 common intervals')
  await expect(cells('A')).toHaveText(['6', '3334', '0'])
  await expect(cells('C')).toHaveText(['2', '3333', '10000'])
  expect((await download()).split('\r\n')[3]).toContain(',6,2,"C",2,3333,10000,')
  await query(6)
  expect(await download()).toBe(early)
  await view.getByLabel('Allocation interval (seconds)').fill('70')
  await run.click()
  await expect(view.getByRole('alert')).toContainText('UTC end on the selected grid')
  expect(await download()).toBe(early)
  await view.getByLabel('Allocation interval (seconds)').fill('60')
  const maximum = view.getByLabel('Maximum weight per listing (bp)')
  await maximum.fill('3333')
  await run.click()
  await expect(view.getByRole('alert')).toContainText('fully allocated portfolio')
  expect(await download()).toBe(early)
  await maximum.fill('6000')
  await run.click()
  await expect(view.getByText('Maximum weight 6000 bp per listing.', { exact: true })).toBeVisible()
  await expect(status).toHaveText('1 of 6 common intervals')
  const cappedEarly = await download()
  expect(cappedEarly.split('\r\n')[0]).toBe(early.split('\r\n')[0] + ',maximum_weight_basis_points')
  expect(cappedEarly.split('\r\n')[3]).toBe(early.split('\r\n')[3] + ',6000')
  await query(7)
  await expect(cells('A')).toHaveText(['6', '3334', '4000'])
  await expect(cells('B')).toHaveText(['6', '3333', '0'])
  await expect(cells('C')).toHaveText(['2', '3333', '6000'])
  const cappedLater = await download()
  expect(cappedLater.split('\r\n')[3]).toMatch(/,6,2,"C",2,3333,6000,.*?,6000$/)
  await query(6)
  expect(await download()).toBe(cappedEarly)
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await page.getByRole('button', { name: 'Return to workspace' }).click()
  expect(await catalogContents(page)).toEqual(original)
})
