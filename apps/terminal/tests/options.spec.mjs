import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures.mjs'
import { catalogContents } from './catalog-fixtures.mjs'

const utc = t => '2025-04-03T' + t + 'Z'
async function open(page) {
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open option chain' }).click()
  await expect(page.getByRole('heading', { name: 'Option chain', exact: true })).toBeFocused()
}

test('offline option surface exposes known quotes, Greeks and unavailable mids', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await open(page)
  await page.getByRole('button', { name: 'Start option demo' }).click()
  const snapshot = page.getByRole('region', { name: 'Option snapshot' })
  const spot = snapshot.getByText('Underlying spot', { exact: true }).locator('xpath=following-sibling::dd')
  const table = snapshot.getByRole('table', { name: 'Option chain results' })
  const row = id => table.getByRole('row', { name: new RegExp('^' + id) })
  await expect(spot).toHaveText('100 USD')
  await expect(row('APR-C100')).toContainText('20.00%')
  await expect(row('APR-C100')).toContainText('0.573496')
  await expect(row('APR-P100')).toContainText('-0.416554')
  await expect(row('APR-C90')).toHaveCount(0)
  const american = page.getByRole('region', { name: 'American exercise pricing' })
  await expect(american).toHaveCount(0)
  await expect(row('APR-C105')).toContainText('Missing bid or ask')
  await expect(row('APR-P110')).toContainText('Crossed spread')
  await expect(row('APR-P75')).toContainText('Midpoint outside model bounds')
  await expect(row('APR-C120')).toContainText('Stale option quote')
  await snapshot.getByText('Implied volatility surface', { exact: true }).click()
  const october = snapshot.getByRole('table', { name: 'Expiry 2025-10-03T14:00:00Z' })
  await expect(october.getByRole('cell').filter({ hasText: '23.00%' })).toHaveCount(2)
  await page.getByRole('button', { name: 'Late option quote' }).click()
  await expect(row('APR-C90')).toContainText('25.00%')
  await expect(row('APR-AM-C90')).toContainText('american')
  await expect(row('APR-AM-C90')).toContainText('American pricing available below')
  const priceAmerican = american.getByRole('button', { name: 'Price American option' })
  const solveAmerican = american.getByRole('button', { name: 'Solve midpoint IV' })
  await priceAmerican.click()
  await expect(american.getByRole('status')).toHaveText('APR-AM-C90 model price 16.247756 USD')
  await solveAmerican.click()
  await expect(american.getByRole('status')).toHaveText('APR-AM-C90 implied volatility 24.96% · model price 16.234568 USD')
  await expect(spot).toHaveText('100 USD')
  await page.getByRole('button', { name: 'Updated underlying' }).click()
  await expect(spot).toHaveText('100.5 USD')
  await expect(american.getByRole('status')).toHaveCount(0)
  await priceAmerican.click()
  await expect(american.getByRole('status')).toHaveText('APR-AM-C90 model price 16.614676 USD')
  await solveAmerican.click()
  await expect(american.getByRole('status')).toHaveText('APR-AM-C90 implied volatility 23.82% · model price 16.234568 USD')
  await expect(row('APR-C100')).not.toContainText('20.00%')
  await page.getByRole('button', { name: 'Late option quote' }).click()
  await expect(american.getByRole('status')).toHaveCount(0)
  await solveAmerican.click()
  await expect(american.getByRole('status')).toContainText('24.96%')
  await page.getByRole('button', { name: 'Corrected spread' }).click()
  await expect(row('APR-P110')).not.toContainText('Crossed spread')
  await page.getByLabel('Known time (UTC)').fill(utc('14:05:00'))
  await page.getByRole('button', { name: 'Run option query' }).click()
  await expect(spot).toHaveText('100.5 USD')
  await page.getByLabel('Effective time (UTC)').fill(utc('14:01:00'))
  await page.getByRole('button', { name: 'Run option query' }).click()
  await expect(spot).toHaveText('101 USD')
  await page.getByRole('button', { name: 'Before late quotes' }).click()
  await expect(row('APR-C90')).toHaveCount(0)
  await expect(american).toHaveCount(0)
  await page.getByLabel('Maximum quote age (seconds)').fill('0')
  await page.getByRole('button', { name: 'Run option query' }).click()
  await expect(row('APR-C100')).toContainText('Stale underlying')
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await expect(page.getByRole('button', { name: 'Open option chain' })).toBeFocused()
})

test('local option data validates identity and preserves the stored catalog', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('heading', { name: 'Research terminal' }).waitFor()
  const original = await catalogContents(page)
  await open(page)
  const read = name => readFile(new URL('../../../crates/core/tests/fixtures/synthetic-option-' + name + '.csv', import.meta.url), 'utf8')
  const [underlying, quotes] = await Promise.all([read('underlying'), read('quotes')])
  const set = (label, name, content) => page.getByLabel(label).setInputFiles({
    name, mimeType: 'text/csv', buffer: Buffer.from(content),
  })
  await set('Underlying CSV', 'underlying.csv', underlying)
  await set('Option quotes CSV', 'quotes.csv', quotes.replace('DEMO:OPT,USD', 'DEMO:OPT,EUR'))
  const load = page.getByRole('button', { name: 'Load option chain' })
  await load.click()
  await expect(page.getByRole('alert')).toContainText('match the underlying and currency')
  await set('Option quotes CSV', 'quotes.csv', quotes)
  await load.click()
  await expect(page.getByText('underlying.csv · quotes.csv', { exact: true })).toBeVisible()
  await page.getByLabel('Effective time (UTC)').fill(utc('14:00:00'))
  await page.getByLabel('Known time (UTC)').fill(utc('14:00:00'))
  await page.getByRole('button', { name: 'Run option query' }).click()
  await expect(page.getByRole('table', { name: 'Option chain results' })).toContainText('APR-C100')
  await page.getByRole('button', { name: 'Return to historical replay' }).click()
  await page.getByRole('button', { name: 'Return to workspace' }).click()
  expect(await catalogContents(page)).toEqual(original)
})

test('cash dividend option pricing replays observed amounts and keeps report provenance offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await open(page)
  await page.getByRole('button', { name: 'Start option demo' }).click()
  const known = page.getByLabel('Known time (UTC)')
  const replay = page.getByRole('button', { name: 'Run option query' })
  const american = page.getByRole('region', { name: 'American exercise pricing' })
  const pricing = american.getByRole('button', { name: 'Price with cash dividends' })
  const rows = american.getByRole('table', { name: 'Applied cash dividends' }).locator('tbody tr')
  async function value(time) {
    await known.fill(utc(time))
    await replay.click()
    await pricing.click()
    const status = american.getByRole('status')
    await expect(status).toContainText('cash dividend model price')
    return Number((await status.textContent()).split(' ').at(-2))
  }
  const early = await value('14:03:59')
  await expect(american.getByText('No future cash dividends are known at these cutoffs.')).toBeVisible()
  const first = await value('14:04:00')
  await expect(rows).toHaveCount(1)
  await expect(rows.first()).toContainText('7 USD')
  const revised = await value('14:06:00')
  await expect(rows).toHaveCount(2)
  await expect(rows.last()).toContainText('9 USD')
  await expect(rows.last()).toContainText('2025-10-08T14:00:00Z')
  await expect(rows.last()).toContainText(utc('14:06:00'))
  expect(early).toBeGreaterThan(first)
  expect(first).toBeGreaterThan(revised)
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  expect(await value('14:04:00')).toBe(first)
})
