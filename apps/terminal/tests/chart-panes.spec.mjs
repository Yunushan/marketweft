import { expect, test } from './fixtures.mjs'
import { downloadWorkspace, microCSV, openImport, selectBackup, submitImport } from './catalog-fixtures.mjs'

test('links two panes by exact UTC time and restores both sets of preferences', async ({ page, browser, baseURL }) => {
  await page.goto('/')
  const compare = page.getByRole('button', { name: 'Compare charts', exact: true })
  await expect(compare).toHaveAttribute('aria-pressed', 'false')
  const legacy = await downloadWorkspace(page)
  expect(legacy.version).toBe(1)
  await compare.click()
  const primary = page.getByRole('region', { name: 'Primary chart pane' })
  const secondary = page.getByRole('region', { name: 'Comparison chart pane' })
  const settings = page.getByRole('group', { name: 'Comparison chart settings' })
  const instrument = settings.getByLabel('Comparison instrument')
  await instrument.selectOption('NASDAQ:MSFT')
  const ema = settings.getByRole('checkbox', { name: 'EMA 9' })
  await ema.check()
  await expect(ema).toBeEnabled()
  const chart = primary.getByLabel(/NVDA interactive candlestick and volume chart/)
  const primaryPlot = primary.getByRole('region', { name: 'Price and volume chart' })
  const secondaryPlot = secondary.getByRole('region', { name: 'Price and volume chart' })
  await chart.hover({ position: { x: 110, y: 60 } })
  await expect(primaryPlot).toHaveAttribute('data-crosshair-time', /^\d+$/)
  const at = await primaryPlot.getAttribute('data-crosshair-time')
  await expect(secondaryPlot).toHaveAttribute('data-crosshair-time', at)
  const secondaryRange = await secondary.getByTestId('viewport').textContent()
  await primary.getByRole('button', { name: 'Zoom in' }).click()
  await expect(secondary.getByTestId('viewport')).toHaveText(secondaryRange)
  const link = settings.getByRole('checkbox', { name: 'Link by UTC' })
  await link.uncheck()
  await expect(link).toBeEnabled()
  await chart.hover({ position: { x: 110, y: 60 } })
  await expect(primaryPlot).toHaveAttribute('data-crosshair-time', /^\d+$/)
  await expect(secondaryPlot).not.toHaveAttribute('data-crosshair-time', /^\d+$/)
  await page.reload()
  await expect(instrument).toHaveValue('NASDAQ:MSFT')
  await expect(ema).toBeChecked()
  await expect(link).not.toBeChecked()
  const backup = await downloadWorkspace(page)
  expect(backup.version).toBe(2)
  expect(backup.manifest.preferences.comparison).toEqual({
    selected: 'NASDAQ:MSFT', sma: true, ema: true, linked: false,
  })
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  const isolated = await browser.newContext({ baseURL })
  try {
    const clean = await isolated.newPage()
    await clean.goto('/')
    const restored = clean.getByRole('group', { name: 'Comparison chart settings' })
    async function restore(bundle) {
      await clean.getByRole('button', { name: 'Workspace backup', exact: true }).click()
      await selectBackup(clean, bundle)
      await clean.getByRole('button', { name: 'Restore workspace', exact: true }).click()
    }
    await restore(backup)
    await expect(restored.getByLabel('Comparison instrument')).toHaveValue('NASDAQ:MSFT')
    await expect(restored.getByRole('checkbox', { name: 'EMA 9' })).toBeChecked()
    await expect(restored.getByRole('checkbox', { name: 'Link by UTC' })).not.toBeChecked()
    await restore(legacy)
    await expect(restored).toHaveCount(0)
  } finally {
    await isolated.close()
  }
})

test('linked panes leave gaps unselected and primary changes preserve the comparison instrument', async ({ page }) => {
  await page.goto('/')
  await openImport(page, 'GAP', microCSV)
  await submitImport(page, 'GAP')
  await page.getByRole('button', { name: 'Select NASDAQ:NVDA' }).click()
  const compare = page.getByRole('button', { name: 'Compare charts' })
  await compare.click()
  const instrument = page.getByLabel('Comparison instrument')
  await instrument.selectOption('LOCAL:GAP')
  await expect(instrument).toHaveValue('LOCAL:GAP')
  const primary = page.getByRole('region', { name: 'Primary chart pane' })
  const secondary = page.getByRole('region', { name: 'Comparison chart pane' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const primaryBox = await primary.boundingBox()
  const secondaryBox = await secondary.boundingBox()
  expect(secondaryBox.x).toBeGreaterThan(primaryBox.x)
  expect(secondaryBox.y).toBe(primaryBox.y)
  const quote = pane => pane.getByRole('region', { name: 'Price and volume chart' })
  for (const [source, target, symbol] of [[primary, secondary, 'NVDA'], [secondary, primary, 'GAP']]) {
    await source.getByLabel(new RegExp('^' + symbol + ' interactive')).hover({ position: { x: 110, y: 60 } })
    await expect(quote(source)).toHaveAttribute('data-crosshair-time', /^\d+$/)
    await expect(quote(target)).not.toHaveAttribute('data-crosshair-time', /^\d+$/)
  }
  await page.getByRole('button', { name: 'Select NASDAQ:AAPL' }).click()
  await expect(primary.getByLabel(/^AAPL interactive/)).toBeVisible()
  await expect(instrument).toHaveValue('LOCAL:GAP')
})
