import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures.mjs'
import { catalogContents } from './catalog-fixtures.mjs'

test('offline formula backtesting audits missing signals and delayed fills in both execution modes', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  const original = await catalogContents(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open bar backtest' }).click()
  await page.getByRole('button', { name: 'Start backtest demo' }).click()
  await page.getByText('Formula paper backtest', { exact: true }).click()
  const panel = page.getByRole('region', { name: 'Formula paper backtest' })
  const entry = panel.getByRole('textbox', { name: 'Entry formula', exact: true })
  const exit = panel.getByRole('textbox', { name: 'Exit formula', exact: true })
  const known = panel.getByLabel('Formula known cutoff (UTC)')
  const run = panel.getByRole('button', { name: 'Run formula backtest' })
  const signals = panel.getByRole('table', { name: 'Formula signal evaluations' })
  const receipts = panel.getByRole('table', { name: 'Formula backtest receipts' })
  const status = panel.getByRole('status')
  const cash = () => panel.getByText('Formula cash', { exact: true }).locator('..').locator('dd')
  const cut = async time => { await known.fill('2025-04-03T' + time + 'Z'); await run.click() }
  const download = async () => {
    const pending = page.waitForEvent('download')
    await panel.getByRole('button', { name: 'Download formula backtest' }).click()
    const saved = await pending
    expect(saved.suggestedFilename()).toBe('formula-paper-backtest.csv')
    return readFile(await saved.path(), 'utf8')
  }
  await entry.fill('if(close >= 13, 1, 0 / 0)')
  await cut('14:05:00')
  await expect(status).toHaveText('5 observed bars · 0 accepted fills · Language v1')
  await expect(signals.getByRole('row', { name: /^2025-04-03T14:01:00Z/ })).toContainText('Unavailable')
  await expect(receipts.getByRole('rowheader')).toHaveText(['SUBMIT-4'])
  await expect(cash()).toHaveText('1000')
  const first = await download()
  expect(first).toContain('"if(close >= 13, 1, 0 / 0)"')
  expect(first).toMatch(/,0,,1,sell\r\n/)
  await cut('14:06:00')
  await expect(cash()).toHaveText('1000')
  await cut('14:07:00')
  await expect(cash()).toHaveText('969.8')
  await cut('14:11:00')
  await expect(status).toHaveText('10 observed bars · 4 accepted fills · Language v1')
  await expect(cash()).toHaveText('957.8')
  await panel.getByLabel('Formula execution source').selectOption('trades')
  await panel.getByRole('button', { name: 'Use formula sample trades' }).click()
  await cut('14:11:10')
  await expect(status).toHaveText('10 observed bars · 5 accepted fills · Language v1')
  await expect(cash()).toHaveText('957.8')
  expect(await download()).toContain('TRADE-9007199254741000')
  await panel.getByLabel('Formula execution source').selectOption('bars')
  await cut('14:05:00')
  expect(await download()).toEqual(first)
  await exit.fill('lag(close, -1)')
  await run.click()
  await expect(panel.getByRole('alert')).toContainText('Exit formula:')
  expect(await download()).toEqual(first)
  await expect.poll(() => catalogContents(page)).toEqual(original)
})
