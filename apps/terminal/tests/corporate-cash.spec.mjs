test('paper successor delivery journal connects exact reversals to their accepted fill offline', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline ready', { exact: true })).toBeVisible()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Historical replay' }).click()
  await page.getByRole('button', { name: 'Open universe replay' }).click()
  await page.getByRole('button', { name: 'Start corporate cash demo' }).click()
  await page.getByText('Cross-sectional paper replay', { exact: true }).click()
  const view = page.getByRole('region', { name: 'Cross-sectional paper replay', exact: true })
  await view.getByRole('button', { name: 'Use sample liquidity' }).click()
  await view.getByText('Corporate cash reports', { exact: true }).click()
  await view.getByRole('button', { name: 'Use sample corporate reports' }).click()
  await view.getByRole('button', { name: 'Use sample successor share terms' }).click()
  const query = async (effective, known) => {
    await page.getByLabel('Effective time (UTC)').fill(utc(effective))
    await page.getByLabel('Known time (UTC)').fill(known)
    await page.getByRole('button', { name: 'Run as-of query' }).click()
  }
  await query(6, '2025-06-02T14:05:30Z')
  await view.getByRole('button', { name: 'Run ranking replay' }).click()
  await view.getByText('Paper successor delivery journal', { exact: true }).click()
  await expect(view.getByText('No successor share deliveries posted at these cutoffs.')).toBeVisible()
  await query(5, utc(6))
  await expect(view.getByText('No successor share deliveries posted at these cutoffs.')).toBeVisible()
  const postings = view.getByRole('table', { name: 'Paper successor delivery journal', exact: true }).locator('tbody tr')
  const download = async () => {
    const pending = page.waitForEvent('download')
    await view.getByRole('button', { name: 'Download paper successor delivery journal' }).click()
    const file = await pending
    expect(file.suggestedFilename()).toBe('paper-successor-delivery-journal.csv')
    return readFile(await file.path(), 'utf8')
  }
  await query(6, utc(6))
  await expect(postings).toHaveCount(1)
  await expect(postings.first().getByRole('cell', { name: '4/3', exact: true })).toHaveCount(2)
  const receipt = await postings.first().getByRole('cell').last().textContent()
  expect(receipt).toMatch(/^E-\d+$/)
  const receipts = view.getByRole('table', { name: 'Cross-sectional paper receipts', exact: true })
  await expect(receipts.getByRole('rowheader', { name: receipt, exact: true }).locator('..')).toContainText('Q-9007199254740996')
  const first = await download()
  expect(first).toContain('"Synthetic paper liquidity","Synthetic paper successor share terms"')
  expect(first.endsWith(`,4,3,4,3,"${receipt}"\r\n`)).toBe(true)
  await query(6, utc(7))
  await expect(postings).toHaveCount(2)
  await expect(postings.nth(1).getByRole('cell', { name: '-4/3', exact: true })).toBeVisible()
  expect((await download()).endsWith(`,-4,3,0,1,"${receipt}"\r\n`)).toBe(true)
  await query(6, utc(8))
  await expect(postings).toHaveCount(2)
  await query(6, utc(6))
  expect(await download()).toBe(first)
})
